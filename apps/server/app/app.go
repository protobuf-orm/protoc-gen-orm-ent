package app

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"text/template"

	"github.com/protobuf-orm/protobuf-orm/graph"
	"github.com/protobuf-orm/protoc-gen-orm-ent/internal/work"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/reflect/protoreflect"
)

type App struct {
	namer *template.Template

	ent protogen.GoImportPath
	gfs map[string]*protogen.GeneratedFile
}

func New(ent protogen.GoImportPath, opts ...Option) (*App, error) {
	a := &App{
		ent: ent,
		gfs: map[string]*protogen.GeneratedFile{},
	}
	for _, opt := range opts {
		opt(a)
	}
	if a.namer == nil {
		a.namer = template.Must(template.New("namer").Parse("ent/{{ .Name }}.go"))
	}

	return a, nil
}

func (a *App) Run(ctx context.Context, p *protogen.Plugin, g *graph.Graph) error {
	ok := true
	handle_err := func(err error) {
		ok = false
	}

	w := work.NewWork()

	// Every message first, and the work after. An edge may point at an entity
	// declared in a later file, and a map filled as the work goes has nothing
	// to say about one that has not been reached yet.
	for _, f := range p.Files {
		for _, m := range f.Messages {
			w.Imports[m.Desc.FullName()] = m.GoIdent.GoImportPath
		}
	}

	needs := needsOf(g)
	for _, f := range p.Files {
		for _, m := range f.Messages {
			entity, ok := g.Entities[m.Desc.FullName()]
			if !ok {
				continue
			}

			gf, _, err := a.newGeneratedSchemaFile(p, f)
			if err != nil {
				handle_err(err)
				continue
			}

			fw := work.NewFileWork(w, f, entity, gf)
			if err := a.doWork(ctx, fw, needs); err != nil {
				handle_err(err)
				continue
			}
		}
	}
	if !ok {
		return errors.New("some tasks are failed")
	}

	return nil
}

type fileWork struct {
	*work.FileWork
	ent protogen.GoImportPath
}

func (a *App) doWork(ctx context.Context, base *work.FileWork, needs needs) error {
	w := &fileWork{
		FileWork: base,
		ent:      work.At(base.Src.GoImportPath, string(a.ent)),
	}

	w.xServer()
	rpcs := w.Entity.Rpcs()
	writes := rpcs.HasPatch() || rpcs.HasApply()
	if rpcs.HasAdd() || writes || rpcs.HasErase() {
		w.xSnapshots()
	}
	if rpcs.HasAdd() {
		w.xAdd()
	}
	if rpcs.HasGet() {
		w.xGet()
		w.xSelectKey()
		w.xSelectedFields()
		w.xSelect()
		w.xSelectInit()
	}
	// Patch and Apply are two verbs and one write: Patch converts its request
	// into a document and runs the path Apply runs. That path is not the Apply
	// RPC, so it is here for either of them, and the RPC only where there is
	// an Apply.
	name := w.Entity.FullName()
	if rpcs.HasPatch() {
		w.xPatch()
	}
	if needs.key[name] {
		w.xGetKey()
	}
	if writes {
		w.xApplyColumns()
	}
	if rpcs.HasApply() {
		w.xApply()
	}
	if writes {
		w.xApplyPath()
	}
	if rpcs.HasErase() {
		w.xErase()
	}
	if needs.pick[name] {
		w.xPick()
	}

	return nil
}

// needs says, of each entity, which of the functions a verb leans on are
// written for it.
//
// They are not only its own verbs': an Add or a Patch that points an edge at a
// row resolves the target's Ref to a key with the target's <Entity>GetKey, and
// a Pick by a unique index over an edge composes the target's <Entity>Pick.
// So each is asked of what calls it, wherever that is.
type needs struct {
	// <Entity>GetKey: its own write path, and every write of another entity
	// that points an edge at it.
	key map[protoreflect.FullName]bool
	// <Entity>Pick: Get, Erase, GetKey, and every Pick that composes it.
	pick map[protoreflect.FullName]bool
}

func needsOf(g *graph.Graph) needs {
	n := needs{
		key:  map[protoreflect.FullName]bool{},
		pick: map[protoreflect.FullName]bool{},
	}
	for name, e := range g.Entities {
		rpcs := e.Rpcs()
		writes := rpcs.HasPatch() || rpcs.HasApply()
		if writes {
			n.key[name] = true
		}
		if writes || rpcs.HasAdd() {
			for ed := range e.Edges() {
				if !ed.IsList() {
					n.key[ed.Target().FullName()] = true
				}
			}
		}
	}
	for name, e := range g.Entities {
		rpcs := e.Rpcs()
		if n.key[name] || rpcs.HasGet() || rpcs.HasErase() {
			n.pick[name] = true
		}
	}
	for grew := true; grew; {
		grew = false
		for name, e := range g.Entities {
			if !n.pick[name] {
				continue
			}
			for idx := range e.Indexes() {
				if !idx.IsUnique() {
					continue
				}
				for p := range idx.Props() {
					ed, ok := p.(graph.Edge)
					if !ok || n.pick[ed.Target().FullName()] {
						continue
					}
					n.pick[ed.Target().FullName()] = true
					grew = true
				}
			}
		}
	}
	return n
}

func (a *App) newGeneratedSchemaFile(p *protogen.Plugin, f *protogen.File) (*protogen.GeneratedFile, string, error) {
	dir, name := work.Split(f.GeneratedFilenamePrefix)

	var b bytes.Buffer
	if err := a.namer.Execute(&b, struct{ Name string }{Name: name}); err != nil {
		return nil, "", fmt.Errorf("name %s: %w", f.GeneratedFilenamePrefix, err)
	}

	path := string(work.At(protogen.GoImportPath(dir), b.String()))

	gf, ok := a.gfs[path]
	if ok {
		return gf, path, nil
	}

	pkg := work.Dir(path)

	gf = p.NewGeneratedFile(path, pkg)
	a.gfs[path] = gf

	gf.P(`// Code generated by protoc-gen-orm-ent. DO NOT EDIT.`)
	gf.P(`// source: `, f.Desc.Path())
	gf.P("")
	gf.P("package ", work.Base(pkg))
	gf.P("")

	return gf, path, nil
}
